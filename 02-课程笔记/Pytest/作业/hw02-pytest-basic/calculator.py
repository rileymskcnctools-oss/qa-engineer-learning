class Calculator:

    # add(x, y): 执行加法运算
    # subtract(x, y): 执行减法运算
    # multiply(x, y): 执行乘法运算
    # divide(x, y): 执行除法运算
    @staticmethod
    def add( a, b):
        return a + b

    @staticmethod
    def subtract( a, b):
        return a - b

    @staticmethod
    def multiply( a, b):
        return a * b

    @staticmethod
    def divide(a, b):
        return a / b

